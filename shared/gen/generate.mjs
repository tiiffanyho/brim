#!/usr/bin/env node
// Generates shared/gen/events.ts and shared/gen/events.gen.hpp from shared/events.schema.json.
// No dependencies. Supports exactly the JSON-Schema subset used by the schema:
//   string enums, objects with primitive / $ref / array-of fields, `const` discriminators,
//   and oneOf unions with x-discriminator.
// Usage: node shared/gen/generate.mjs          (write files)
//        node shared/gen/generate.mjs --check  (exit 1 if files are stale; used by CI)
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const schemaPath = join(here, "..", "events.schema.json");
const schema = JSON.parse(readFileSync(schemaPath, "utf8"));
const defs = schema.$defs;
const version = schema["x-schema-version"] ?? 1;
const HEADER = "GENERATED by shared/gen/generate.mjs from shared/events.schema.json. DO NOT EDIT.";

const refName = (ref) => ref.replace("#/$defs/", "");
const kindOf = (d) => (d.enum ? "enum" : d.oneOf ? "union" : d.type === "object" ? "object" : "unknown");
const pascal = (s) => s.split(/[_\-\s]/).map((p) => p[0].toUpperCase() + p.slice(1)).join("");
const upperSnake = (s) => s.replace(/([a-z0-9])([A-Z])/g, "$1_$2").toUpperCase();

for (const [name, d] of Object.entries(defs)) {
  if (kindOf(d) === "unknown") throw new Error(`Unsupported def ${name}`);
}

// ---------------------------------------------------------------- TypeScript
function tsType(p) {
  if (p.const !== undefined) return JSON.stringify(p.const);
  if (p.$ref) return refName(p.$ref);
  if (p.type === "array") return `${tsType(p.items)}[]`;
  if (p.type === "integer" || p.type === "number") return "number";
  if (p.type === "string") return "string";
  if (p.type === "boolean") return "boolean";
  throw new Error(`Unsupported property ${JSON.stringify(p)}`);
}
function tsDoc(desc, indent = "") {
  return desc ? `${indent}/** ${desc} */\n` : "";
}
function genTs() {
  let out = `// ${HEADER}\n/* eslint-disable */\n\nexport const SCHEMA_VERSION = ${version};\n\n`;
  for (const [name, d] of Object.entries(defs)) {
    const k = kindOf(d);
    if (k === "enum") {
      out += tsDoc(d.description);
      out += `export type ${name} = ${d.enum.map((v) => JSON.stringify(v)).join(" | ")};\n`;
      out += `export const ${upperSnake(name)}_VALUES: readonly ${name}[] = ${JSON.stringify(d.enum)} as const;\n\n`;
    } else if (k === "object") {
      out += tsDoc(d.description);
      out += `export interface ${name} {\n`;
      const req = new Set(d.required ?? []);
      for (const [f, p] of Object.entries(d.properties)) {
        out += tsDoc(p.description, "  ");
        out += `  ${f}${req.has(f) ? "" : "?"}: ${tsType(p)};\n`;
      }
      out += `}\n\n`;
    } else if (k === "union") {
      const members = d.oneOf.map((m) => refName(m.$ref));
      const disc = d["x-discriminator"];
      out += tsDoc(d.description);
      out += `export type ${name} = ${members.join(" | ")};\n`;
      const consts = members.map((m) => defs[m].properties[disc].const);
      out += `export type ${name}Type = ${name}["${disc}"];\n`;
      out += `export const ${upperSnake(name)}_TYPES: readonly ${name}Type[] = ${JSON.stringify(consts)} as const;\n`;
      out += `export function is${name}(x: unknown): x is ${name} {\n`;
      out += `  return typeof x === "object" && x !== null && (${upperSnake(name)}_TYPES as readonly string[]).includes((x as { ${disc}?: string }).${disc} ?? "");\n}\n\n`;
    }
  }
  return out;
}

// ---------------------------------------------------------------- C++
function cppType(p) {
  if (p.$ref) return refName(p.$ref);
  if (p.type === "array") return `std::vector<${cppType(p.items)}>`;
  if (p.type === "integer") return "std::int64_t";
  if (p.type === "number") return "double";
  if (p.type === "string") return "std::string";
  if (p.type === "boolean") return "bool";
  throw new Error(`Unsupported property ${JSON.stringify(p)}`);
}
function cppDefault(p) {
  if (p.$ref) return "{}";
  if (p.type === "integer" || p.type === "number") return " = 0";
  if (p.type === "boolean") return " = false";
  return "";
}
function genCpp() {
  let out = `// ${HEADER}\n#pragma once\n\n`;
  out += `#include <cstdint>\n#include <optional>\n#include <string>\n#include <string_view>\n#include <type_traits>\n#include <vector>\n\n`;
  out += `#include "common/json.hpp"\n\nnamespace brim::schema {\n\n`;
  out += `using brim::json::Value;\ninline constexpr int kSchemaVersion = ${version};\n\n`;

  // enums first
  for (const [name, d] of Object.entries(defs)) {
    if (kindOf(d) !== "enum") continue;
    if (d.description) out += `// ${d.description}\n`;
    out += `enum class ${name} { ${d.enum.map(pascal).join(", ")} };\n`;
    out += `inline const char* to_string(${name} v) {\n  switch (v) {\n`;
    for (const e of d.enum) out += `    case ${name}::${pascal(e)}: return "${e}";\n`;
    out += `  }\n  return "";\n}\n`;
    out += `inline bool from_string(std::string_view s, ${name}& out) {\n`;
    for (const e of d.enum) out += `  if (s == "${e}") { out = ${name}::${pascal(e)}; return true; }\n`;
    out += `  return false;\n}\n\n`;
  }

  out += `namespace detail {
inline Value enc(const std::string& v) { return Value(v); }
inline Value enc(std::int64_t v) { return Value(v); }
inline Value enc(double v) { return Value(v); }
inline Value enc(bool v) { return Value(v); }
template <class E, std::enable_if_t<std::is_enum_v<E>, int> = 0>
Value enc(E v) { return Value(to_string(v)); }
template <class T>
auto enc(const T& v) -> decltype(to_json(v)) { return to_json(v); }
template <class T>
Value enc(const std::vector<T>& v) { Value a = Value::array(); for (const auto& x : v) a.push_back(enc(x)); return a; }

inline bool dec(const Value& j, std::string& out) { if (!j.is_string()) return false; out = j.as_string(); return true; }
inline bool dec(const Value& j, std::int64_t& out) { if (!j.is_number()) return false; out = j.as_int(); return true; }
inline bool dec(const Value& j, double& out) { if (!j.is_number()) return false; out = j.as_double(); return true; }
inline bool dec(const Value& j, bool& out) { if (!j.is_bool()) return false; out = j.as_bool(); return true; }
template <class E, std::enable_if_t<std::is_enum_v<E>, int> = 0>
bool dec(const Value& j, E& out) { return j.is_string() && from_string(j.as_string(), out); }
template <class T>
auto dec(const Value& j, T& out) -> decltype(from_json(j, out, nullptr)) { return from_json(j, out, nullptr); }
template <class T>
bool dec(const Value& j, std::vector<T>& out) {
  if (!j.is_array()) return false;
  out.clear();
  for (const auto& x : j.as_array()) { T t{}; if (!dec(x, t)) return false; out.push_back(std::move(t)); }
  return true;
}
inline bool fail(std::string* err, const char* type, const char* field) {
  if (err) *err = std::string(type) + ": missing or invalid field '" + field + "'";
  return false;
}
}  // namespace detail

`;

  // forward-declare structs + functions so nested refs work in any order
  const objects = Object.entries(defs).filter(([, d]) => kindOf(d) === "object");
  for (const [name] of objects) out += `struct ${name};\n`;
  out += "\n";
  for (const [name] of objects) {
    out += `inline Value to_json(const ${name}& v);\n`;
    out += `inline bool from_json(const Value& j, ${name}& out, std::string* err = nullptr);\n`;
  }
  out += "\n";

  // topological order: struct fields of struct type must be complete
  const ordered = [];
  const seen = new Set();
  const visit = (name) => {
    if (seen.has(name)) return;
    seen.add(name);
    for (const p of Object.values(defs[name].properties)) {
      const r = p.$ref ? refName(p.$ref) : p.items?.$ref ? refName(p.items.$ref) : null;
      if (r && kindOf(defs[r]) === "object") visit(r);
    }
    ordered.push(name);
  };
  for (const [name] of objects) visit(name);

  for (const name of ordered) {
    const d = defs[name];
    const req = new Set(d.required ?? []);
    if (d.description) out += `// ${d.description}\n`;
    out += `struct ${name} {\n`;
    for (const [f, p] of Object.entries(d.properties)) {
      if (p.const !== undefined) {
        out += `  static constexpr const char* k${pascal(f)} = "${p.const}";\n`;
        continue;
      }
      const t = cppType(p);
      const comment = p.description ? `  // ${p.description}` : "";
      if (req.has(f)) out += `  ${t} ${f}${cppDefault(p)};${comment}\n`;
      else out += `  std::optional<${t}> ${f};${comment}\n`;
    }
    out += `};\n\n`;
  }

  for (const name of ordered) {
    const d = defs[name];
    const req = new Set(d.required ?? []);
    out += `inline Value to_json(const ${name}& v) {\n  Value o = Value::object();\n`;
    for (const [f, p] of Object.entries(d.properties)) {
      if (p.const !== undefined) out += `  o.set("${f}", Value("${p.const}"));\n`;
      else if (req.has(f)) out += `  o.set("${f}", detail::enc(v.${f}));\n`;
      else out += `  if (v.${f}) o.set("${f}", detail::enc(*v.${f}));\n`;
    }
    out += `  return o;\n}\n`;
    out += `inline bool from_json(const Value& j, ${name}& out, std::string* err) {\n`;
    out += `  if (!j.is_object()) { if (err) *err = "${name}: not an object"; return false; }\n`;
    for (const [f, p] of Object.entries(d.properties)) {
      if (p.const !== undefined) {
        out += `  { const Value* x = j.find("${f}"); if (!x || !x->is_string() || x->as_string() != "${p.const}") return detail::fail(err, "${name}", "${f}"); }\n`;
      } else if (req.has(f)) {
        out += `  { const Value* x = j.find("${f}"); if (!x || !detail::dec(*x, out.${f})) return detail::fail(err, "${name}", "${f}"); }\n`;
      } else {
        out += `  { const Value* x = j.find("${f}"); if (x && !x->is_null()) { ${cppType(p)} t{}; if (!detail::dec(*x, t)) return detail::fail(err, "${name}", "${f}"); out.${f} = std::move(t); } else { out.${f}.reset(); } }\n`;
      }
    }
    out += `  return true;\n}\n\n`;
  }

  for (const [name, d] of Object.entries(defs)) {
    if (kindOf(d) !== "union") continue;
    const disc = d["x-discriminator"];
    const members = d.oneOf.map((m) => refName(m.$ref));
    out += `// Discriminator for ${name} (field "${disc}").\n`;
    out += `enum class ${name}Type { ${members.map((m) => pascal(defs[m].properties[disc].const)).join(", ")} };\n`;
    out += `inline std::optional<${name}Type> ${name.replace(/^./, (c) => c.toLowerCase())}_type_of(const Value& j) {\n`;
    out += `  const Value* t = j.find("${disc}");\n  if (!t || !t->is_string()) return std::nullopt;\n  const std::string& s = t->as_string();\n`;
    for (const m of members) {
      const c = defs[m].properties[disc].const;
      out += `  if (s == "${c}") return ${name}Type::${pascal(c)};\n`;
    }
    out += `  return std::nullopt;\n}\n\n`;
  }

  out += `}  // namespace brim::schema\n`;
  return out;
}

const outputs = [
  [join(here, "events.ts"), genTs()],
  [join(here, "events.gen.hpp"), genCpp()],
];
const check = process.argv.includes("--check");
let stale = false;
for (const [path, content] of outputs) {
  const current = existsSync(path) ? readFileSync(path, "utf8") : "";
  if (current === content) continue;
  if (check) {
    console.error(`stale: ${path} (run: node shared/gen/generate.mjs)`);
    stale = true;
  } else {
    writeFileSync(path, content);
    console.log(`wrote ${path}`);
  }
}
if (stale) process.exit(1);
if (check) console.log("shared/gen is up to date");
